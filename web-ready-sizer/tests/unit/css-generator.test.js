"use strict";

const test = require("node:test");
const assert = require("node:assert");

global.WRS = {};

require("../../client/js/lib/data/tailwind-data.js");
require("../../client/js/lib/data/tailwind-colors.js");
require("../../client/js/lib/engine/conversion-engine.js");
const cssGenerator = require("../../client/js/lib/engine/css-generator.js");

function rectangle(overrides) {
    return Object.assign({
        index: 0,
        type: "PathItem",
        name: "Rectangle",
        width: 80,
        height: 24,
        x: 10,
        y: 20,
        opacity: 100,
        fill: { type: "rgb", r: 30, g: 41, b: 59 },
        stroke: { type: "rgb", r: 20, g: 184, b: 166, width: 2 },
        cornerRadius: 8
    }, overrides || {});
}

function text(overrides) {
    return rectangle(Object.assign({
        type: "TextFrame",
        name: "Heading",
        width: 320,
        height: 48,
        fill: { type: "rgb", r: 226, g: 232, b: 240 },
        stroke: { type: "none", width: 0 },
        cornerRadius: 0,
        text: {
            contents: "Hello",
            font: "Alexandria",
            style: "Regular",
            sizePt: 36,
            weightGuess: 700,
            tracking: 0,
            leadingPt: 48,
            horizontalScale: 100,
            justification: "left",
            caseStyle: "uppercase",
            mixedStyles: false
        }
    }, overrides || {}));
}

test("generateClasses produces the expected Tailwind set for a rectangle", () => {
    const classes = cssGenerator.generateClasses(rectangle());
    assert.ok(classes.includes("w-20"));
    assert.ok(classes.includes("h-6"));
    assert.ok(classes.includes("bg-slate-800"));
    assert.ok(classes.includes("border-2"));
    assert.ok(classes.includes("border-teal-500"));
    assert.ok(classes.includes("rounded-lg"));
});

test("generateClasses includes typography for text frames", () => {
    const classes = cssGenerator.generateClasses(text());
    assert.ok(classes.includes("text-5xl"));
    assert.ok(classes.includes("font-bold"));
    assert.ok(classes.includes("text-uppercase"));
});

test("generateClasses de-duplicates its output", () => {
    const classes = cssGenerator.generateClasses(rectangle());
    const unique = Array.from(new Set(classes));
    assert.deepStrictEqual(classes, unique);
});

test("generateCssDeclaration emits px by default", () => {
    const css = cssGenerator.generateCssDeclaration(rectangle(), {});
    assert.match(css, /width: 80px;/);
    assert.match(css, /height: 24px;/);
    assert.match(css, /background-color: #1E293B;/);
    assert.match(css, /border-radius: 8px;/);
});

test("generateCssDeclaration emits rem when requested", () => {
    const css = cssGenerator.generateCssDeclaration(rectangle(), { useRem: true });
    assert.match(css, /width: 5rem;/);
    assert.match(css, /height: 1.5rem;/);
    assert.match(css, /border-radius: 0.5rem;/);
});

test("generateHtml produces a div with classes", () => {
    const html = cssGenerator.generateHtml(rectangle());
    assert.match(html, /<div class="[^"]*w-20/);
    assert.match(html, /data-w="80"/);
});

test("generateHtml produces a paragraph for text", () => {
    const html = cssGenerator.generateHtml(text());
    assert.match(html, /<p class="/);
    assert.match(html, />Hello</);
});

test("generateHtml escapes text content", () => {
    const html = cssGenerator.generateHtml(text({
        text: Object.assign({}, text().text, { contents: "<b>&\"x\"" })
    }));
    assert.match(html, /&lt;b&gt;&amp;&quot;x&quot;/);
});

test("generateCssDocument includes a header and every rule", () => {
    const css = cssGenerator.generateCssDocument(
        [rectangle(), text()],
        { documentName: "Test.ai", baseline: 16 }
    );
    assert.match(css, /Generated by Web-Ready Sizer/);
    assert.match(css, /Test\.ai/);
    assert.match(css, /width: 80px;/);
});

test("generateTailwindConfig emits valid JS with custom tokens", () => {
    const config = cssGenerator.generateTailwindConfig({
        colors: [{ hex: "#14B8A6" }],
        spacing: [16, 80],
        fontSizes: []
    });
    assert.match(config, /^module\.exports = \{/);
    assert.match(config, /brand-14b8a6/);
    assert.match(config, /ds-0/);
});

test("generateDesignTokens returns valid JSON with colour and typography", () => {
    const tokens = JSON.parse(cssGenerator.generateDesignTokens([rectangle(), text()], {}));
    assert.strictEqual(tokens.$type, undefined);
    assert.ok(tokens.color["color-1e293b"]);
    assert.ok(tokens.typography["font-48"]);
    assert.strictEqual(tokens.typography["font-48"].$value.fontSize, "48px");
});

test("hexFromColor handles rgb, none and gradients", () => {
    assert.strictEqual(cssGenerator.hexFromColor({ type: "rgb", r: 255, g: 0, b: 0 }), "#FF0000");
    assert.strictEqual(cssGenerator.hexFromColor({ type: "none" }), null);
    assert.strictEqual(cssGenerator.hexFromColor({ type: "gradient", stops: [] }), null);
});

test("safeSelector produces stable slugged class names", () => {
    const selector = cssGenerator.safeSelector(rectangle());
    assert.match(selector, /^path-rectangle-0$/);
});

test("RTL width/justification mapping is applied when rtl is enabled", () => {
    const ltr = cssGenerator.generateClasses(text({ text: Object.assign({}, text().text, { justification: "left" }) }), { rtl: false });
    const rtl = cssGenerator.generateClasses(text({ text: Object.assign({}, text().text, { justification: "left" }) }), { rtl: true });
    assert.ok(ltr.includes("text-start"));
    assert.ok(rtl.includes("text-end"));
});
